CREATE TABLE IF NOT EXISTS core.neighborhoods (
    enterprise_id TEXT PRIMARY KEY,
    facility_id TEXT NOT NULL UNIQUE,
    object_id INTEGER NOT NULL UNIQUE,
    internal_id INTEGER NOT NULL UNIQUE,
    neighborhood_name TEXT NOT NULL,
    source_method TEXT,
    source_last_updated TIMESTAMPTZ,
    notes TEXT,
    source_shape_length DOUBLE PRECISION,
    source_shape_area DOUBLE PRECISION,
    geom_repaired BOOLEAN NOT NULL DEFAULT false,
    geom geometry(MultiPolygon, 4326) NOT NULL,
    source_id BIGINT NOT NULL REFERENCES metadata.source_registry(source_id)
);

CREATE TABLE IF NOT EXISTS core.parks (
    facility_id TEXT PRIMARY KEY,
    object_id INTEGER NOT NULL UNIQUE,
    internal_id INTEGER NOT NULL UNIQUE,
    gis_object_id DOUBLE PRECISION,
    park_name TEXT NOT NULL,
    address TEXT,
    park_type_code TEXT NOT NULL,
    park_class_code TEXT NOT NULL,
    subclass_code TEXT,
    current_status TEXT NOT NULL,
    date_opened DATE,
    deed_date DATE,
    council_district INTEGER,
    park_district INTEGER,
    all_acres NUMERIC,
    developed_acres NUMERIC,
    undeveloped_acres NUMERIC,
    open_space_acres NUMERIC,
    water_acres NUMERIC,
    owner TEXT,
    name_alias TEXT,
    location_id TEXT,
    planning_area TEXT,
    specific_plan_area TEXT,
    panel_number TEXT,
    hyperlink TEXT,
    adoptable_code TEXT,
    adoption_status TEXT,
    park_count_code TEXT,
    maintained_by_code TEXT,
    contract_code TEXT,
    source_last_updated TIMESTAMPTZ,
    source_shape_length DOUBLE PRECISION,
    source_shape_area DOUBLE PRECISION,
    geom geometry(MultiPolygon, 4326) NOT NULL,
    source_id BIGINT NOT NULL REFERENCES metadata.source_registry(source_id)
);

CREATE TABLE IF NOT EXISTS core.schools (
    cds_code CHAR(14) PRIMARY KEY,
    nces_district_id TEXT,
    nces_school_id TEXT,
    status_type TEXT NOT NULL,
    county_name TEXT NOT NULL,
    district_name TEXT NOT NULL,
    school_name TEXT,
    street TEXT,
    city TEXT,
    zip_code TEXT,
    state TEXT,
    phone TEXT,
    website TEXT,
    open_date DATE,
    closed_date DATE,
    charter_code TEXT,
    charter_number TEXT,
    funding_type TEXT,
    district_ownership_code TEXT,
    district_ownership_type TEXT,
    school_ownership_code TEXT,
    school_ownership_type TEXT,
    education_option_code TEXT,
    education_option_name TEXT,
    education_level_code TEXT,
    education_level_name TEXT,
    grades_offered TEXT,
    grades_served TEXT,
    virtual_code TEXT,
    magnet_code TEXT,
    year_round_code TEXT,
    federal_district_id TEXT,
    multilingual_code TEXT,
    source_last_updated DATE,
    geom geometry(Point, 4326),
    source_id BIGINT NOT NULL REFERENCES metadata.source_registry(source_id),
    CONSTRAINT school_coordinate_pair CHECK (
        geom IS NOT NULL OR school_name IS NULL
    )
);
